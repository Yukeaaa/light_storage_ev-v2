def clean_text(s):
    # 注意：必须先做引用替换，再剥离段标【a-e】——否则 "§4.1【b】" 会先变成 "§4.1" 而使具体规则失配。
    for a, b in REPS:
        s = re.sub(a, b, s)
    s = re.sub(r"【[a-e]】", "", s)
    s = s.replace("STOPPED", "NOT_RUNNING")
    s = s.replace("**", "")
    s = re.sub(r"^\s*-{3,}\s*$", "", s, flags=re.M)   # 去水平分隔线
    s = re.sub(r"[ \t]+\n", "\n", s)
    s = re.sub(r"\n{3,}", "\n\n", s)
    return s.strip("\n")


def demote(body):
    out = []
    for l in body:
        m = re.match(r"^(#{3,6})\s+(.*)$", l)
        if m:
            t = re.sub(r"^[0-9]+(\.[0-9]+)*\s+", "", m.group(2))
            out.append("#" * min(len(m.group(1)) + 2, 6) + " " + t)
        else:
            out.append(l)
    return out


def emit(level, title, body):
    body = demote(strip_notes(body))
    txt = clean_text("\n".join(body))
    return f"{level} {title}\n\n{txt}\n\n"


