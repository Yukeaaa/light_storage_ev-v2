def top_sections(lines):
    """按 '## N. 标题' 切分顶级章节；遇非编号 '## ' 标题（附录/待决事项等）即截断，其内容不进提交稿。"""
    secs, cur = [], None
    for ln in lines:
        if re.match(r"^##\s", ln):
            m = re.match(r"^##\s+(\d+)\.\s+(.*)$", ln)
            if m:
                if cur:
                    secs.append(cur)
                cur = [int(m.group(1)), m.group(2), []]
            else:
                if cur:
                    secs.append(cur)
                cur = None
            continue
        if cur is not None:
            cur[2].append(ln)
    if cur:
        secs.append(cur)
    return secs


def sub_sections(body):
    secs, cur = [], None
    for ln in body:
        m = re.match(r"^###\s+(.*)$", ln)
        if m:
            if cur:
                secs.append(cur)
            cur = [m.group(1), []]
        else:
            if cur is not None:
                cur[1].append(ln)
    if cur:
        secs.append(cur)
    return secs


def strip_notes(body):
    out = [l for l in body if not l.lstrip().startswith(">")]
    res, blank = [], 0
    for l in out:
        if l.strip() == "":
            blank += 1
            if blank > 1:
                continue
        else:
            blank = 0
        res.append(l)
    while res and res[0].strip() == "":
        res.pop(0)
    while res and res[-1].strip() == "":
        res.pop()
    return res


